#!/usr/bin/env node
/**
 * Installs the OpenCode plugin.
 *
 * Bundles `src/adapters/opencode.ts` (with the shared core) into a single,
 * self-contained `.js` file and places it in OpenCode's global plugins dir
 * (`~/.config/opencode/plugins/`) so it is auto-loaded on startup.
 *
 * Config is shared with the Pi extension: `~/.pi/agent/safety.json` (or a
 * project-local `safety.json`, or `AGENT_SAFETY_CONFIG`).
 *
 * Usage: node scripts/install-opencode.mjs [--dir <plugins dir>]
 */

import { build } from "esbuild";
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const root = resolve(dirname(require.resolve("../package.json")));

const flagIdx = process.argv.indexOf("--dir");
const pluginsDir =
  flagIdx !== -1
    ? resolve(process.argv[flagIdx + 1])
    : join(homedir(), ".config", "opencode", "plugins");
const outfile = join(pluginsDir, "agent-safety.js");

mkdirSync(pluginsDir, { recursive: true });

async function main() {
  await build({
    entryPoints: [join(root, "src/adapters/opencode.ts")],
    outfile,
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node22",
    sourcemap: false,
    logLevel: "info",
  });
  if (!existsSync(outfile)) {
    console.error(`[agent-safety] bundle missing: ${outfile}`);
    process.exit(1);
  }
  writeFileSync(
    join(pluginsDir, "README.txt"),
    [
      "agent-safety OpenCode plugin (auto-generated by install-opencode.mjs).",
      "Undo: delete agent-safety.js from this directory.",
      "Config: ~/.pi/agent/safety.json (see agent-safety README).",
    ].join("\n")
  );
  console.log(`[agent-safety] installed OpenCode plugin → ${outfile}`);
}

main().catch((err) => {
  console.error("[agent-safety] install failed:", err);
  process.exit(1);
});